"""Export the SCons source graph to Studio's managed GNU Make project."""
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

METADATA_GROUPS = {
    'OpenMV5', 'OpenMV_VFS', 'OpenMV_CSI', 'OpenMV_ImageHelpers',
    'OpenMV_StdIO', 'OpenMV_Peripherals', 'OpenMV_AprilTagResult', 'OpenMV_EthosU55',
    'OpenMV_Vision', 'OpenMV_Vision_AprilTagResult',
}


def flag_text(value):
    return value if isinstance(value, str) else ' '.join(map(str, value))


def project_roots(root):
    """Map the SDK layout to Eclipse resources without copying shared sources."""
    root = Path(root).resolve()
    sdk = root.parents[1]
    roots = {'': root}
    shared = {'rt-thread': sdk / 'rt-thread', 'libraries': sdk / 'libraries'}
    for name, directory in shared.items():
        if not (root / name).exists() and directory.is_dir():
            roots[name] = directory
    return roots


def resource_path(root, path):
    path = Path(path).resolve()
    for name, directory in project_roots(root).items():
        try:
            relative = path.relative_to(directory).as_posix()
            return name + '/' + relative if name else relative
        except ValueError:
            pass
    raise ValueError('Source/include path is outside the project SDK: ' + str(path))


def update_sdk_links(root):
    tree = ET.parse(root / '.project')
    parent = tree.getroot().find('linkedResources')
    if parent is None:
        parent = ET.SubElement(tree.getroot(), 'linkedResources')
    names = ('rt-thread', 'libraries', 'ra', 'ra_cfg', 'ra_gen', 'FSPConfiguration', 'configuration.xml')
    for item in list(parent):
        if item.findtext('name') in names:
            parent.remove(item)
    resources = {name: path for name, path in project_roots(root).items() if name}
    for name, path in resources.items():
        item = ET.SubElement(parent, 'link')
        ET.SubElement(item, 'name').text = name
        ET.SubElement(item, 'type').text = '2' if path.is_dir() else '1'
        relative = path.relative_to(root.parents[1]).as_posix()
        ET.SubElement(item, 'locationURI').text = 'PARENT-2-PROJECT_LOC/' + relative
    ET.indent(tree, space='  ')
    tree.write(root / '.project', encoding='UTF-8', xml_declaration=True)


def build_settings(root, env, projects, config):
    from building import GetDepend
    root = Path(root).resolve()

    def relative(value):
        return os.path.relpath(str(value), root).replace('\\', '/')

    sources, metadata = {}, {}
    for group in projects:
        common = flag_text(group.get('LOCAL_CCFLAGS', ''))
        local = env.Clone(CPPDEFINES=group.get('LOCAL_CPPDEFINES', []),
                          CPPPATH=group.get('LOCAL_CPPPATH', []))
        common += ' ' + local.subst('$_CPPDEFFLAGS $_CPPINCFLAGS')
        for node in group['src']:
            source = Path(node.srcnode().abspath)
            if source.suffix not in ('.c', '.cc', '.cpp', '.s', '.S'):
                continue
            name = relative(source)
            language = ('CXX' if source.suffix in ('.cc', '.cpp') else
                        'AS' if source.suffix in ('.s', '.S') else 'C')
            flags = (common + ' ' + flag_text(group.get('LOCAL_' + language + 'FLAGS', ''))).strip()
            sources[name] = flags
            if group['name'] in METADATA_GROUPS and source.suffix in ('.c', '.cc', '.cpp'):
                metadata[name] = flags
    return dict(
        sources=dict(sorted(sources.items())), metadata_sources=dict(sorted(metadata.items())),
        include_dirs=[relative(item) for item in env['CPPPATH']],
        native_sources={resource_path(root, root / name): flags for name, flags in sorted(sources.items())},
        native_include_dirs=[resource_path(root, item) for item in env['CPPPATH']],
        defines=list(env.get('CPPDEFINES', [])), cflags=flag_text(env['CFLAGS']),
        cxxflags=flag_text(env['CXXFLAGS']), asflags=flag_text(env['ASFLAGS']),
        compiler=str(Path(config.EXEC_PATH) / config.CC),
        ml_enabled=bool(GetDepend('BSP_USING_OPENMV_ML')),
    )


def write_changed(path, value):
    data = value.encode('utf-8')
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def write_build_tools(root, compiler):
    # Recursive Make must use the same compiler as metadata generation/package.
    # Studio may otherwise put a long (or older) ARM toolchain path first.
    directory = Path(compiler).parent.as_posix().replace('$', '$$').replace('#', '\\#')
    write_changed(root / 'build/make/tools.mk',
                  '# Generated by OpenMV project export/preparation.\n'
                  'OPENMV_PYTHON ?= "' + Path(sys.executable).as_posix() + '"\n'
                  'export PATH := ' + directory + os.pathsep + '$(PATH)\n')


def resolve_project_name(root, requested=None):
    """A plain Studio 'scons --target=eclipse' must not rename the project."""
    if requested:
        return requested
    project = root / '.project'
    existing = ET.parse(project).findtext('name') if project.is_file() else None
    if existing and existing != 'project':
        return existing
    preference = root / '.settings/projcfg.ini'
    if preference.is_file():
        match = re.search(r'(?m)^project_name=(.+)$', preference.read_text(encoding='utf-8'))
        if match:
            return match.group(1).strip()
    return existing or root.name


def configure_language_settings(root):
    """Prevent CDT from treating preprocessed C/C++ declarations as paths.

    GCC writes include-search paths to stderr, while -dD writes declarations
    from forced headers to stdout. CDT merges these streams and can interpret
    declarations as include directories. -dM emits only macro definitions.
    """
    path = root / '.settings/language.settings.xml'
    tree = ET.parse(path) if path.is_file() else ET.ElementTree(ET.Element('project'))
    for config in ET.parse(root / '.cproject').findall('./storageModule/cconfiguration'):
        identity = config.get('id')
        data = next((item for item in tree.getroot().findall('configuration')
                     if item.get('id') == identity), None)
        if data is None:
            module = config.find('storageModule')
            data = ET.SubElement(tree.getroot(), 'configuration', id=identity,
                                 name=module.get('name', 'Debug'))
        extension = data.find('extension')
        if extension is None:
            extension = ET.SubElement(data, 'extension', point='org.eclipse.cdt.core.LanguageSettingsProvider')
        if not list(extension):
            ET.SubElement(extension, 'provider', {'copy-of': 'extension',
                          'id': 'org.eclipse.cdt.ui.UserLanguageSettingsProvider'})
            for provider_id in ('org.eclipse.cdt.core.ReferencedProjectsLanguageSettingsProvider',
                                'org.eclipse.cdt.managedbuilder.core.MBSLanguageSettingsProvider'):
                ET.SubElement(extension, 'provider-reference', id=provider_id, ref='shared-provider')
        identity = 'ilg.gnuarmeclipse.managedbuild.cross.GCCBuiltinSpecsDetector'
        provider = next((item for item in extension if item.get('id') == identity), None)
        if provider is None:
            provider = ET.SubElement(extension, 'provider', id=identity)
        provider.tag = 'provider'
        for key in ('copy-of', 'ref'):
            provider.attrib.pop(key, None)
        provider.attrib.update({
            'class': 'org.eclipse.cdt.managedbuilder.language.settings.providers.GCCBuiltinSpecsDetector',
            'console': 'false', 'env-hash': '0', 'keep-relative-paths': 'false',
            'name': 'CDT ARM Cross GCC Built-in Compiler Settings', 'prefer-non-shared': 'true',
            'parameter': '${COMMAND} ${FLAGS} ${cross_toolchain_flags} -E -P -v -dM "${INPUTS}"',
        })
        for item in list(provider):
            provider.remove(item)
        for language in ('org.eclipse.cdt.core.gcc', 'org.eclipse.cdt.core.g++'):
            ET.SubElement(provider, 'language-scope', id=language)
    ET.indent(tree, space='  ')
    write_changed(path, '<?xml version="1.0" encoding="UTF-8" standalone="no"?>\n' +
                  ET.tostring(tree.getroot(), encoding='unicode') + '\n')


def native_flags(value):
    # Managed Make runs inside Debug/Release instead of the project root.
    return value.replace('platform/', '../platform/')


def source_exclusions(root, sources):
    """CDT also compiles .cc; the stock RT-Thread exporter only filters .c/.cpp."""
    selected = set(sources)
    parents = {parent.as_posix() for name in selected for parent in Path(name).parents}
    excluded = []
    for prefix, base in project_roots(root).items():
        if prefix and prefix not in parents:
            excluded.append(prefix)
            continue
        for directory, subdirs, files in os.walk(base):
            relative = Path(prefix) / Path(directory).relative_to(base)
            for name in list(subdirs):
                item = (relative / name).as_posix()
                if item not in parents:
                    excluded.append(item)
                    subdirs.remove(name)
            for name in files:
                item = (relative / name).as_posix()
                if Path(name).suffix in ('.c', '.cc', '.cpp', '.s', '.S') and item not in selected:
                    excluded.append(item)
    return sorted(excluded)


def configure_cproject(root, settings):
    tree = ET.parse(root / '.cproject')
    for config in tree.findall('./storageModule/cconfiguration/storageModule/configuration'):
        config.set('artifactName', 'rtthread')
        for key in ('prebuildStep', 'postbuildStep', 'preannouncebuildStep', 'postannouncebuildStep'):
            config.attrib.pop(key, None)
        chain = config.find('folderInfo/toolChain')
        builder = chain.find('builder')
        builder.set('managedBuildOn', 'true')
        builder.set('name', 'GNU Make Builder')
        builder.set('buildPath', '${workspace_loc:/${ProjName}/Debug}')
        builder.set('cleanBuildTarget', 'clean2')
        builder.set('incrementalBuildTarget', 'openmv-all')
        builder.set('autoBuildTarget', 'openmv-all')
        for key in ('command', 'arguments'):
            builder.attrib.pop(key, None)
        for option in chain.findall('option'):
            name = option.get('superClass', '')
            if name.endswith('addtools.createflash'):
                option.set('value', 'false')
            elif name.endswith('arm.target.fpu.unit'):
                option.set('value', 'ilg.gnuarmeclipse.managedbuild.cross.option.arm.target.fpu.unit.default')
        compilers = {}
        for tool in chain.findall('tool'):
            name = tool.get('superClass', '')
            kind = ('c' if name.endswith('.c.compiler') else
                    'cpp' if name.endswith('.cpp.compiler') else
                    'assembler' if name.endswith('.assembler') else None)
            if kind:
                compilers[kind] = tool
                if kind != 'assembler':
                    # CDT emits -MT<file>.d for per-file overrides. Also name the
                    # object so changes to generated/ordinary headers rebuild it.
                    tool.set('commandLinePattern', '${COMMAND} ${cross_toolchain_flags} ${FLAGS} -MT"$@" -c ${OUTPUT_FLAG} ${OUTPUT_PREFIX}${OUTPUT} ${INPUTS}')
                suffix = '.assembler.other' if kind == 'assembler' else '.' + kind + '.compiler.other'
                flags = settings[{'c': 'cflags', 'cpp': 'cxxflags', 'assembler': 'asflags'}[kind]]
                for option in tool.findall('option'):
                    if option.get('superClass', '').endswith(suffix):
                        option.set('value', native_flags(flags) +
                                   (' -include ../rtconfig_preinc.h' if kind == 'assembler' else ''))
                    if option.get('superClass', '').endswith('.include.paths'):
                        for child in list(option):
                            option.remove(child)
                        # SCons prepends machine/storage overrides. Sorting these
                        # like the stock exporter does selects the wrong FSP headers.
                        for directory in settings.get('native_include_dirs', settings['include_dirs']):
                            ET.SubElement(option, 'listOptionValue', builtIn='false',
                                          value='"${workspace_loc:/${ProjName}/' + directory + '}"')
            if '.linker' in name:
                tool.set('commandLinePattern', '${COMMAND} ${cross_toolchain_flags} ${FLAGS} ${OUTPUT_FLAG} ${OUTPUT_PREFIX}${OUTPUT} @objects.list $(USER_OBJS) $(LIBS)')
                for option in tool.findall('option'):
                    if option.get('superClass', '').endswith('.linker.other'):
                        option.set('value', '-mcpu=cortex-m85 -mthumb -mfloat-abi=hard --specs=nosys.specs -Wl,-u,Reset_Handler -L..')
        # Preserve each group's local flags and private preprocessor definitions.
        for item in list(config.findall('fileInfo')):
            if '.openmv.' in item.get('id', ''):
                config.remove(item)
        native_sources = settings.get('native_sources', settings['sources'])
        for source, flags in native_sources.items():
            if not flags.strip():
                continue
            kind = ('cpp' if Path(source).suffix in ('.cc', '.cpp') else
                    'assembler' if Path(source).suffix in ('.s', '.S') else 'c')
            parent = compilers[kind]
            identity = config.get('id') + '.openmv.' + hashlib.sha256(source.encode()).hexdigest()[:12]
            info = ET.SubElement(config, 'fileInfo', id=identity, name=Path(source).name,
                                 rcbsApplicability='disable', resourcePath=source)
            tool = ET.SubElement(info, 'tool', id=identity + '.tool',
                                 name=parent.get('name'), superClass=parent.get('id'))
            base = settings[{'cpp': 'cxxflags', 'assembler': 'asflags', 'c': 'cflags'}[kind]]
            suffix = '.assembler.other' if kind == 'assembler' else '.' + kind + '.compiler.other'
            if kind == 'assembler':
                base += ' -include ../rtconfig_preinc.h'
            ET.SubElement(tool, 'option', id=identity + '.flags',
                          superClass='ilg.gnuarmeclipse.managedbuild.cross.option' + suffix,
                          name='Other compiler flags', valueType='string',
                          value=native_flags(base + ' ' + flags))
        entry = config.find('sourceEntries/entry')
        custom = [item for item in entry.get('excluding', '').split('|')
                  if item and not item.startswith('//')]
        excluded = ['//' + item for item in source_exclusions(root, native_sources)]
        entry.set('excluding', '|'.join(dict.fromkeys(custom + excluded)))
    ET.indent(tree, space='  ')
    write_changed(root / '.cproject', '<?xml version="1.0" encoding="UTF-8" standalone="no"?>\n'
                  '<?fileVersion 4.0.0?>\n' + ET.tostring(tree.getroot(), encoding='unicode') + '\n')


def export_project(root, env, projects, config, reset=False, project_name=None):
    import eclipse
    root = Path(root).resolve()
    project_name = resolve_project_name(root, project_name)
    settings = build_settings(root, env, projects, config)
    # CDT needs the generated translation unit to exist when it discovers files.
    frozen = root / 'build/generated/frozen_content.c'
    if not frozen.exists():
        write_changed(frozen, '/* Generated by the OpenMV Make preparation step. */\n')
    env['project'] = projects
    relative_path = eclipse.RelativeProjectPath
    excluding = eclipse.GenExcluding
    eclipse.RelativeProjectPath = lambda unused_env, path: resource_path(root, path)
    # Use the exact graph, including .cc, and avoid traversing SDK build/report copies.
    eclipse.GenExcluding = lambda unused_env, unused_project: source_exclusions(root, settings['native_sources'])
    try:
        eclipse.TargetEclipse(env, reset, project_name)
    finally:
        eclipse.RelativeProjectPath = relative_path
        eclipse.GenExcluding = excluding
    update_sdk_links(root)
    configure_cproject(root, settings)
    configure_language_settings(root)
    write_changed(root / 'build/make/settings.json', json.dumps(settings, indent=2) + '\n')
    write_build_tools(root, settings['compiler'])
    preference = root / '.settings/projcfg.ini'
    text = preference.read_text(encoding='utf-8')
    write_changed(preference, re.sub(r'(?m)^is_use_scons_build=.*$', 'is_use_scons_build=False', text))
    for launch in (root / '.settings').glob('*.rttlaunch'):
        text = launch.read_text(encoding='utf-8')
        text = text.replace('build/firmware/rtthread.elf', 'Debug/rtthread.elf')
        write_changed(launch, text)
    print('OpenMV Studio: managed GNU Make (openmv-all); no SCons at build time')
